-- Schema inicial do Sistema de Gestão de Academia (Amazon RDS PostgreSQL)
BEGIN;

CREATE TABLE IF NOT EXISTS planos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(80) NOT NULL,
    descricao VARCHAR(500) NOT NULL DEFAULT '',
    preco NUMERIC(10,2) NOT NULL CHECK (preco > 0),
    duracao_dias INTEGER NOT NULL CHECK (duracao_dias >= 1),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS alunos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plano_id BIGINT NOT NULL REFERENCES planos(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(160) NOT NULL,
    telefone VARCHAR(40),
    data_nascimento DATE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT alunos_email_lowercase CHECK (email = LOWER(email))
);

CREATE UNIQUE INDEX IF NOT EXISTS alunos_email_unique_lower_idx ON alunos (LOWER(email));
CREATE INDEX IF NOT EXISTS alunos_plano_id_idx ON alunos (plano_id);

COMMIT;
